/**
 * utils/gemini.js
 * Travel Assistant backend utility powered by Google Gemini Flash.
 * Securely keeps API keys and model configuration on the server.
 */

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function getApiKey() {
    if (!process.env.GEMINI_API_KEY || process.env.GEMINI_API_KEY === "YOUR_GEMINI_API_KEY") {
        try {
            require("dotenv").config({ override: true });
        } catch (_) {}
    }
    return process.env.GEMINI_API_KEY;
}

function getModel() {
    const model = process.env.GEMINI_MODEL;
    return (model && model !== "YOUR_GEMINI_FLASH_MODEL" && model.trim() !== "")
        ? model.trim()
        : "gemini-3.1-flash-lite";
}

/**
 * Checks if a real, valid API key is present
 */
function isKeyConfigured() {
    const key = getApiKey();
    return Boolean(
        key &&
        key !== "YOUR_GEMINI_API_KEY" &&
        key.trim() !== ""
    );
}

/**
 * Execute call to Gemini REST API securely from server with retry & error handling:
 * - 429 / quota: no retry, returns clear quota message
 * - 503 / temporary network errors: capped exponential backoff (waitTime = (2 ** attempt) + 2)
 * - Max 3 attempts, server logging of retries, no API key exposure
 */
async function callGemini(prompt) {
    if (!isKeyConfigured()) {
        return null;
    }

    const apiKey = getApiKey();
    const model = getModel();
    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;
    const maxRetries = 3;

    for (let attempt = 0; attempt < maxRetries; attempt++) {
        // Capped exponential backoff: waitTime = (2 ** attempt) + 2 seconds
        const waitTimeSec = Math.min((2 ** attempt) + 2, 30);
        const waitTimeMs = waitTimeSec * 1000;

        try {
            const response = await fetch(endpoint, {
                method: "POST",
                headers: {
                    "Content-Type": "application/json",
                    "x-goog-api-key": apiKey
                },
                body: JSON.stringify({
                    contents: [
                        {
                            parts: [{ text: prompt }]
                        }
                    ],
                    generationConfig: {
                        temperature: 0.7,
                        maxOutputTokens: 1500
                    }
                })
            });

            // 429 Quota / Rate Limit reached: do NOT retry; immediately return a clear message
            if (response.status === 429) {
                console.warn("[Gemini Assistant] HTTP 429 Quota / Rate limit reached. Aborting retries.");
                throw new Error("Gemini API rate limit or quota has been reached. Please check your usage quota or try again in a few moments.");
            }

            // 503 or 5xx temporary server/availability errors: use capped exponential backoff
            if (response.status === 503 || response.status === 502 || response.status === 504 || response.status === 500) {
                const errorBody = await response.text();
                const isQuota = errorBody.toLowerCase().includes("quota") || errorBody.toLowerCase().includes("exhausted");
                if (isQuota) {
                    throw new Error("Gemini API rate limit or quota has been reached. Please check your usage quota or try again in a few moments.");
                }

                if (attempt < maxRetries - 1) {
                    console.log(`[Gemini Assistant] HTTP ${response.status} temporary server error. Attempt ${attempt + 1}/${maxRetries}. Retrying in ${waitTimeSec}s (exponential backoff)...`);
                    await sleep(waitTimeMs);
                    continue;
                } else {
                    console.warn(`[Gemini Assistant] All ${maxRetries} retry attempts failed for HTTP ${response.status}.`);
                    throw new Error("Unable to reach Gemini AI service due to temporary high server demand. Please try again shortly.");
                }
            }

            if (!response.ok) {
                const errorText = await response.text();
                if (errorText.toLowerCase().includes("quota") || errorText.toLowerCase().includes("exhausted")) {
                    throw new Error("Gemini API rate limit or quota has been reached. Please check your usage quota or try again in a few moments.");
                }
                throw new Error(`Gemini service error (${response.status})`);
            }

            const data = await response.json();
            const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
            if (!text) {
                throw new Error("No response generated by Gemini model.");
            }
            return text;

        } catch (err) {
            // Quota / rate limit errors: abort immediately without retrying
            if (err.message && err.message.includes("rate limit or quota")) {
                throw err;
            }

            // Check for temporary network / SSL / connection errors
            const errMsg = (err.message || "").toLowerCase();
            const isNetworkError = err.code === "ECONNRESET" ||
                                   err.code === "ETIMEDOUT" ||
                                   err.code === "ENOTFOUND" ||
                                   errMsg.includes("fetch failed") ||
                                   errMsg.includes("network") ||
                                   errMsg.includes("ssl") ||
                                   errMsg.includes("socket") ||
                                   errMsg.includes("disconnected") ||
                                   errMsg.includes("unavailable");

            if (isNetworkError && attempt < maxRetries - 1) {
                console.log(`[Gemini Assistant] Temporary network error (${err.message}). Attempt ${attempt + 1}/${maxRetries}. Retrying in ${waitTimeSec}s (exponential backoff)...`);
                await sleep(waitTimeMs);
                continue;
            }

            if (attempt >= maxRetries - 1) {
                console.warn(`[Gemini Assistant] All ${maxRetries} attempts failed: ${err.message}`);
                if (err.message && err.message.startsWith("Unable to reach Gemini AI service")) {
                    throw err;
                }
                throw new Error("Unable to reach Gemini AI service due to a temporary network issue. Please check your connection and try again.");
            }

            throw err;
        }
    }
}

/**
 * Generates simulated structured plan when placeholder key is used
 */
function generateSimulatedTripPlan({ startLocation, destination, budget, days }) {
    const numDays = Math.max(1, parseInt(days) || 3);
    const dayPlans = [];
    for (let i = 1; i <= numDays; i++) {
        if (i === 1) {
            dayPlans.push(`- **Day 1:** Arrival in ${destination} from ${startLocation}, check-in to accommodation, explore the local market, and enjoy a relaxed welcome dinner.`);
        } else if (i === numDays) {
            dayPlans.push(`- **Day ${i}:** Morning leisure walk / souvenir shopping, local brunch, and return journey towards ${startLocation}.`);
        } else {
            dayPlans.push(`- **Day ${i}:** Full day sightseeing covering top cultural landmarks, famous scenic viewpoints, and authentic regional cuisine.`);
        }
    }

    return `### ✈️ Travel Plan: ${startLocation} → ${destination} (${numDays} Days)

*(Note: Live Google Gemini is configured in .env. To enable real-time AI responses, update \`GEMINI_API_KEY\` in your \`.env\` file. Below is your structured plan based on your inputs.)*

---

#### 1. 🚆 Suggested Way of Travelling
- **Recommended Transit:** Depending on distance, high-speed train or express flight from ${startLocation} to ${destination} is most time-efficient. For scenic routes under 300km, intercity bus or self-drive is a great option.
- **Local Commute:** Use local metro, shared cabs, or rental scooters to keep local transit hassle-free.

#### 2. 🗺️ Approximate Route & Sequence
- **Start:** Departure from **${startLocation}**
- **Transit Hub:** Arrival at ${destination} Central / Airport
- **Zone 1:** Downtown & Heritage District
- **Zone 2:** Scenic Nature / Coastline / Mountain Highlights
- **Return:** Departure from ${destination} back to **${startLocation}**

#### 3. 📍 Key Places to Visit
- **Historic & Cultural:** Iconic local monuments and heritage buildings
- **Scenic Highlights:** Popular viewpoints, waterfronts, or nature parks
- **Food & Shopping:** Famous street food lanes and vibrant evening craft bazaars

#### 4. 📅 Day-wise Travel Plan
${dayPlans.join("\n")}

#### 5. 💡 Budget-Aware Suggestions (${budget ? `Budget: ${budget}` : "Cost-Effective Tips"})
- **Accommodation:** Book verified Wanderlust homestays or boutique stays slightly away from tourist epicenters to save 25–40%.
- **Dining:** Eat at popular local eateries and verified street vendors rather than hotel restaurants for authentic flavor at a fraction of the cost.
- **Passes:** Check for public transit day passes or combined attraction tickets.`;
}


/**
 * Plan a trip using Gemini Flash with retry & error handling
 */
async function planTrip({ startLocation, destination, budget, days }) {
    const prompt = `You are Wanderlust's Travel Assistant, a friendly and knowledgeable AI travel planner.
Create a simple, structured travel plan for:
- Starting Location: ${startLocation}
- Travel Destination: ${destination}
- Approximate Budget: ${budget || "Moderate"}
- Duration: ${days || 3} days

Please structure your response with these exact sections:
1. 🚆 Suggested Way of Travelling (transit options, route)
2. 🗺️ Approximate Route & Sequence
3. 📍 Key Places to Visit
4. 📅 Day-wise Travel Plan (Day 1 to Day ${days})
5. 💡 Budget-Aware Suggestions (money-saving tips, food, stay)

Keep the response concise, engaging, and cleanly formatted with bullet points.`;

    try {
        const liveResponse = await callGemini(prompt);
        if (liveResponse) {
            return { plan: liveResponse, isLive: true };
        }
    } catch (err) {
        console.warn(`[Gemini Assistant] Error handled: ${err.message}`);
        return {
            plan: `⚠️ **Travel Assistant Notice:** ${err.message}`,
            isLive: false,
            error: err.message
        };
    }

    return {
        plan: generateSimulatedTripPlan({ startLocation, destination, budget, days }),
        isLive: false
    };
}

